// Precompiles the contracts' Ajv validators into standard JS code.
// The web app validates exactly as before at the system boundary, but without loading the
// Ajv compiler or compiling schemas in the browser (fewer bytes and less CPU).
//
// Generates one module per chunk that uses it (docs/UX_REDESIGN.md §6.1: each chunk pays only for its own):
// - validators.generated.js: snapshot (candidate, manifest, profile). Goes in the main chunk.
// - validators.discovery.generated.js: search results and background catalog of the
//   v3 snapshot (ADR-008). Separate chunk: the loader imports it only if the snapshot is v3.
// - validators.analogs.generated.js: reference analogs catalog (loaded with the catalog).
//
// The mission contracts (mission-request/evaluation/export/ai, ADR-009) are NOT precompiled here:
// shared/mission validates them with Ajv at runtime, inside the deferred mission chunk (ADR-013).
//
// Usage: node scripts/build-validators.mjs [--check]   (--check fails if any file is out of date)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import addFormats from 'ajv-formats'
import standaloneCode from 'ajv/dist/standalone/index.js'

const here = dirname(fileURLToPath(import.meta.url))
const contracts = resolve(here, '../../../contracts')
const domain = resolve(here, '../src/domain')
const schema = (name) => JSON.parse(readFileSync(resolve(contracts, name), 'utf8'))

/** Output file → { exported name: schema }. */
const OUTPUTS = {
  'validators.generated.js': {
    validateCandidate: 'candidate-site.schema.json',
    validateManifest: 'data-manifest.schema.json',
    validateProfile: 'mission-profile.schema.json',
  },
  'validators.discovery.generated.js': {
    validateSearch: 'discovery-search.schema.json',
    validatePrecedents: 'precedent-catalog.schema.json',
  },
  'validators.analogs.generated.js': {
    validateReferenceAnalogs: 'reference-analog.schema.json',
  },
}

export function generate(exportsToFiles) {
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true, lines: true } })
  addFormats(ajv)
  const refs = {}
  for (const [name, file] of Object.entries(exportsToFiles)) {
    const loaded = schema(file)
    ajv.addSchema(loaded)
    refs[name] = loaded.$id
  }
  const code = standaloneCode(ajv, refs)
  // Ajv emits require() for two runtime dependencies; they are converted to ESM imports.
  const imports = new Map()
  const esm = code
    .replace(/^"use strict";\n/m, '')
    .replace(/require\("([^"]+)"\)(\.default)?/g, (_, module, isDefault) => {
      const key = `${module}${isDefault ?? ''}`
      if (!imports.has(key)) imports.set(key, { name: `__dep${imports.size}`, module, isDefault: Boolean(isDefault) })
      const { name } = imports.get(key)
      return isDefault ? `__interop(${name})` : name
    })
  const header = [...imports.values()]
    .map(({ name, module }) => `import * as ${name} from '${module}.js'`)
    .concat(
      // CommonJS interop: Vite honors __esModule and Node does not; both are kept in the exported function.
      "const __interop = (m) => (typeof m.default === 'function' ? m.default : m.default?.default ?? m)",
    )
    .join('\n')
  return `/* eslint-disable */\n// GENERATED by scripts/build-validators.mjs from contracts/*.schema.json. Do not edit by hand.\n${header}\n${esm.trimEnd()}\n`
}

const check = process.argv.includes('--check')
let stale = false
for (const [file, entries] of Object.entries(OUTPUTS)) {
  const out = resolve(domain, file)
  const code = generate(entries)
  if (!check) {
    writeFileSync(out, code)
    continue
  }
  let current = ''
  try {
    current = readFileSync(out, 'utf8')
  } catch {
    current = ''
  }
  if (current !== code) {
    console.error(`${file} is out of date: run node scripts/build-validators.mjs`)
    stale = true
  }
}
if (stale) process.exit(1)
